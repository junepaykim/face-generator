def nation_name(nation: int | None) -> str | None:
    """The country for a nation's database ID; None where it is not known."""
    found = NATIONS.get(nation) if nation is not None else None
    return found.name if found else None


def region_of(nation: int | None) -> str | None:
    """The look region for a nation's database ID; None: draw from the world's mix."""
    found = NATIONS.get(nation) if nation is not None else None
    return found.region if found else None
